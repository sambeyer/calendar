"""Photo inventory: JPEG inspection, the photos.lock manifest, and verification.

The photos themselves are not in git. ``calendars/<year>/photos.lock`` records, for each
photo a bird entry refers to, its SHA-256, pixel size, colour profile and EXIF orientation.
Every build checks the files on disk against that manifest and refuses on any mismatch.
"""

from __future__ import annotations

import hashlib
import io
from collections import Counter
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

import pypdf
import yaml
from PIL import Image, ImageCms, UnidentifiedImageError

EXIF_ORIENTATION_TAG = 0x0112
LOCK_FILENAME = "photos.lock"


class PhotoError(Exception):
    """A photo is unusable or does not match the lock. The message names the file."""


@dataclass(frozen=True)
class JpegInfo:
    width: int
    height: int
    colour_profile: str | None
    orientation: int
    sha256: str
    size_bytes: int


@dataclass(frozen=True)
class LockRecord:
    file: str
    sha256: str
    width: int
    height: int
    colour_profile: str | None
    orientation: int


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _profile_description(icc: bytes) -> str | None:
    try:
        profile = ImageCms.ImageCmsProfile(io.BytesIO(icc))
        description = ImageCms.getProfileDescription(profile).strip()
    except (ImageCms.PyCMSError, OSError, ValueError):
        return None
    return description or None


def inspect_jpeg(path: Path) -> JpegInfo:
    """Check a file is an 8-bit RGB JPEG and read what the lock needs.

    The PDF embeds these exact bytes, so anything the PDF cannot honour is refused here:
    non-JPEG files, non-RGB colour, and an EXIF orientation other than 1 (PDF ignores EXIF,
    so a rotated photo would print sideways).
    """
    try:
        with Image.open(path) as img:
            if img.format != "JPEG":
                raise PhotoError(f"{path.name}: not a JPEG (found {img.format})")
            if img.mode != "RGB":
                raise PhotoError(f"{path.name}: must be RGB, found {img.mode}")
            width, height = img.size
            orientation = int(img.getexif().get(EXIF_ORIENTATION_TAG, 1))
            icc = img.info.get("icc_profile")
            profile = _profile_description(icc) if icc else None
    except UnidentifiedImageError as exc:
        raise PhotoError(f"{path.name}: not a readable image") from exc
    if orientation != 1:
        raise PhotoError(
            f"{path.name}: EXIF orientation is {orientation}; re-export from Lightroom with "
            "the rotation applied (the PDF ignores EXIF orientation)"
        )
    return JpegInfo(
        width=width,
        height=height,
        colour_profile=profile,
        orientation=orientation,
        sha256=sha256_file(path),
        size_bytes=path.stat().st_size,
    )


def read_lock(path: Path) -> dict[str, LockRecord]:
    """Load photos.lock. Returns an empty mapping if the file does not exist."""
    if not path.exists():
        return {}
    data: Any = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    records: dict[str, LockRecord] = {}
    for item in data.get("photos", []):
        record = LockRecord(**item)
        records[record.file] = record
    return records


def write_lock(path: Path, year: int, records: Iterable[LockRecord]) -> None:
    ordered = sorted(records, key=lambda r: r.file)
    payload: dict[str, Any] = {
        "year": year,
        "photos": [
            {
                "file": r.file,
                "sha256": r.sha256,
                "width": r.width,
                "height": r.height,
                "colour_profile": r.colour_profile,
                "orientation": r.orientation,
            }
            for r in ordered
        ],
    }
    header = (
        "# Generated by `birdcal lock-photos`. Do not edit by hand.\n"
        "# Each photo's SHA-256, pixel size, colour profile and EXIF orientation.\n"
    )
    path.write_text(header + yaml.safe_dump(payload, sort_keys=False), encoding="utf-8")


def lock_photos(
    photos_dir: Path, files: Iterable[str], lock_path: Path, year: int
) -> list[LockRecord]:
    """Hash and inspect each named file and write the lock. Refuses if any file is missing."""
    records: list[LockRecord] = []
    missing: list[str] = []
    for name in sorted(set(files)):
        path = photos_dir / name
        if not path.is_file():
            missing.append(name)
            continue
        info = inspect_jpeg(path)
        records.append(
            LockRecord(
                file=name,
                sha256=info.sha256,
                width=info.width,
                height=info.height,
                colour_profile=info.colour_profile,
                orientation=info.orientation,
            )
        )
    if missing:
        raise PhotoError("photos not found in " + str(photos_dir) + ": " + ", ".join(missing))
    write_lock(lock_path, year, records)
    return records


@dataclass(frozen=True)
class PhotoStatus:
    """Whether one referenced photo can be used in this build."""

    file: str
    record: LockRecord | None
    path: Path | None
    problem: str | None  # None when usable
    # Set only under --ignore-lock: why the file was used without matching the lock.
    lock_note: str | None = None

    @property
    def usable(self) -> bool:
        return self.record is not None and self.path is not None and self.problem is None


def check_against_lock(
    photos_dir: Path | None,
    files: Iterable[str],
    locks: Mapping[str, LockRecord],
    *,
    ignore_lock: bool = False,
) -> dict[str, PhotoStatus]:
    """Verify each referenced photo against the lock.

    A file that is absent from disk, or has no lock entry, is reported as a problem (not an
    error) so the caller can decide: draft and proof fall back to a placeholder, print refuses.
    A file that is present but whose hash differs from the lock is always an error, unless
    ``ignore_lock`` is set: then the file on disk is used, its own hash and size are recorded,
    and ``lock_note`` says why it was not verified.
    """
    statuses: dict[str, PhotoStatus] = {}
    for name in sorted(set(files)):
        record = locks.get(name)
        path = photos_dir / name if photos_dir is not None else None
        if path is None:
            statuses[name] = PhotoStatus(
                name, record, None, "paths.photos_dir is not set (local.yaml)"
            )
            continue
        if not path.is_file():
            statuses[name] = PhotoStatus(name, record, None, f"not found in {photos_dir}")
            continue
        if ignore_lock:
            info = inspect_jpeg(path)
            on_disk = LockRecord(
                file=name,
                sha256=info.sha256,
                width=info.width,
                height=info.height,
                colour_profile=info.colour_profile,
                orientation=info.orientation,
            )
            note: str | None = None
            if record is None:
                note = "not in photos.lock"
            elif record.sha256 != on_disk.sha256:
                note = "differs from photos.lock"
            statuses[name] = PhotoStatus(name, on_disk, path, None, lock_note=note)
            continue
        if record is None:
            raise PhotoError(f"{name}: not in photos.lock; run `birdcal lock-photos <year>`")
        actual = sha256_file(path)
        if actual != record.sha256:
            raise PhotoError(
                f"{name}: does not match photos.lock (sha256 {actual[:12]}... expected "
                f"{record.sha256[:12]}...). If the file changed on purpose, run "
                "`birdcal lock-photos <year>` and review the diff."
            )
        statuses[name] = PhotoStatus(name, record, path, None)
    return statuses


def write_resampled_jpeg(src: Path, dst: Path, *, scale: float, quality: int) -> tuple[int, int]:
    """Write a smaller, lower-quality baseline JPEG copy of ``src`` to ``dst``.

    ``scale`` is the linear size factor (at most 1). The colour profile is kept. Returns the
    pixel size of the copy.
    """
    with Image.open(src) as img:
        img.load()
        icc = img.info.get("icc_profile")
        out: Image.Image = img
        if scale < 1:
            size = (max(1, round(img.width * scale)), max(1, round(img.height * scale)))
            out = img.resize(size, Image.Resampling.LANCZOS)
        kwargs: dict[str, Any] = {"quality": quality, "optimize": True}
        if icc:
            kwargs["icc_profile"] = icc
        out.save(dst, "JPEG", **kwargs)
        return out.width, out.height


# pypdf decodes every image it lists (page.images) and refuses any whose decoded buffer
# exceeds its default 75 MB cap. Our source photos are full-page, and a 28-megapixel RGB
# photo already decodes to about 84 MB, so the cap is raised for this read only. Nothing
# is re-encoded: the hashes are taken from the stored JPEG bytes.
_MAX_IMAGE_BUFFER_BYTES = 256_000_000


def embedded_jpeg_hashes(pdf_path: Path) -> Counter[str]:
    """SHA-256 of every DCTDecode image stream in the PDF, as a multiset.

    ``get_data()`` returns the stored bytes for DCT streams, so a match means the JPEG
    was embedded unchanged. Any other image filter is a PhotoError: the pipeline should
    never produce one.
    """
    with pypdf.apply_configuration(image_maximum_buffer_size=_MAX_IMAGE_BUFFER_BYTES):
        return _embedded_jpeg_hashes(pdf_path)


def _embedded_jpeg_hashes(pdf_path: Path) -> Counter[str]:
    hashes: Counter[str] = Counter()
    reader = pypdf.PdfReader(str(pdf_path))
    for page in reader.pages:
        for image in page.images:
            # pypdf's stubs do not type image references; the object is a stream.
            obj: Any = cast(Any, image).indirect_reference.get_object()
            filters = obj.get("/Filter")
            names = [str(f) for f in filters] if isinstance(filters, list) else [str(filters)]
            if names != ["/DCTDecode"]:
                raise PhotoError(f"embedded image uses filter {names}, expected DCTDecode only")
            hashes[hashlib.sha256(obj.get_data()).hexdigest()] += 1
    return hashes
